"""
Test 01: stochastic reactors database generation.

Small H2 stochastic reactors simulation (500 particles, CURL_MODIFIED mixing, mixing pairs read from
pairs_list.pkl / CURL_rate_list.pkl for reproducibility), generated by the session fixture h2_stoch_dtb
(see h2_stoch_database.py, conftest.py) in STOCH_DTB_TEST/solutions.h5.
Check: histograms of the generated states are close to the references in H2_TEST_histograms/.
"""
from misc import extract_h2_dtb_histograms
from h2_stoch_database import tests_dir

import numpy as np
import os


def test_h2_dtb_computation(h2_stoch_dtb):
    os.chdir(h2_stoch_dtb)

    tol = np.array([139.75, 3.74, 50.4, 4.94, 166.15, 9.9, 124.38, 5.9, 4.62, 2.04])
    assert np.max(extract_h2_dtb_histograms("./STOCH_DTB_TEST/solutions.h5", os.path.join(tests_dir, "H2_TEST_histograms"), tol)) < np.float64(0.0)
